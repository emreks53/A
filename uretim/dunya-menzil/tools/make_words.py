"""data/words.json (forced alignment output) -> data/words.js for the browser engine."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
W = json.loads((root / 'data/words.json').read_text())
rows = ',\n'.join(f'  {{ i: {i}, w: {json.dumps(w["w"], ensure_ascii=False)}, s: {w["s"]:.3f}, e: {w["e"]:.3f}{", ar: true" if w["arabic"] else ""} }}' for i, w in enumerate(W))
(root / 'data/words.js').write_text('/* generated by tools/make_words.py from data/words.json (MMS forced alignment) */\nwindow.E = window.E || {};\nE.WORDS = [\n' + rows + '\n];\n')
print(len(W), 'words')
