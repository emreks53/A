    front = box_obj('q_front', -QW / 2, QW / 2, 0, QH, QT - bt, QT, mat=q_cover_mat, bevel=1.0 * MM, segs=3)
    me = front.data
    uvl = me.uv_layers['UVMap']
    for poly in me.polygons:
        for li in poly.loop_indices:
            v = me.vertices[me.loops[li].vertex_index].co
            if poly.normal.z > 0.5:
                uvl.data[li].uv = ((v.x + QW / 2) / QW, v.y / QH)
            else:
                uvl.data[li].uv = (-1, -1)
    pages = box_obj('q_pages', -QW / 2 + 3 * MM, QW / 2 - 0.5 * MM, 3 * MM, QH - 3 * MM, bt, QT - bt, mat=q_pages,
                    bevel=0.5 * MM, segs=2)
    # gently rounded spine on +x
    n = 24
    verts, faces = [], []
    hw = QT / 2
    R = (hw * hw + rbq * rbq) / (2 * rbq)
    th0 = math.asin(hw / R)
    x_base = QW / 2 - 1.0 * MM
    for yv in (0.0, QH):
        for k in range(n + 1):
            a_ = -th0 + 2 * th0 * k / n
            verts.append((x_base + (R * math.cos(a_) - (R - rbq)), yv, hw + R * math.sin(a_)))
        for k in range(n + 1):
            a_ = -th0 + 2 * th0 * k / n
            verts.append((x_base - 2.0 * MM + (R * math.cos(a_) - (R - rbq)), yv, hw + (R * math.sin(a_)) * 0.92))
    m = n + 1
    for k in range(n):
        o0, o1 = k, 2 * m + k
        faces.append((o0, o0 + 1, o1 + 1, o1))
        i0, i1 = m + k, 3 * m + k
        faces.append((i0, i1, i1 + 1, i0 + 1))
        faces.append((o0, i0, i0 + 1, o0 + 1))
        faces.append((o1, o1 + 1, i1 + 1, i1))
    sp = mesh_obj('q_spine', verts, faces, smooth=True, mat=q_plain_mat)
    for ob in (back, front, pages, sp):
        ob.parent = parent
    return parent
