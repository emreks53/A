    t = NT(mat)
    out = t.n('ShaderNodeOutputMaterial')
    tc = t.n('ShaderNodeTexCoord')
    mp = t.n('ShaderNodeMapping'); t.l(tc.outputs['UV'], mp.inputs['Vector'])
    mp.inputs['Rotation'].default_value = (0, 0, rotate)
