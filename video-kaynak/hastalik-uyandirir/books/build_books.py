def chaikin(pts, it=2):
    P = np.asarray(pts, float)
    for _ in range(it):
        Q = [P[0]]
        for a, b in zip(P[:-1], P[1:]):
            Q.append(0.75 * a + 0.25 * b)
            Q.append(0.25 * a + 0.75 * b)
        Q.append(P[-1])
        P = np.array(Q)
    return P


def spine_profile(T, rb):
    """Outer spine profile (x, y) from the left joint to the right joint.
    Spine apex at y=-rb, shoulders at y=0, boards start at y=g. Returns pts, arc slice."""
    hw = T / 2
    R = (hw * hw + rb * rb) / (2 * rb)
    th0 = math.asin(min(hw / R, 1.0))
    n_arc = 44
    ph = np.linspace(-th0, th0, n_arc)
    arc = np.stack([R * np.sin(ph), -(R * np.cos(ph) - (R - rb))], 1)
    g = 3.6 * MM
    dg = 1.25 * MM
    groove_r = np.array([[hw, 0.0], [hw - 0.25 * dg, 0.30 * g], [hw - dg, 0.58 * g],
                         [hw - 0.55 * dg, 0.86 * g], [hw - 0.05 * MM, g + 1.6 * MM]])
    groove_r = chaikin(groove_r, 3)[1:]
    groove_l = groove_r[::-1].copy()
    groove_l[:, 0] *= -1
    pts = np.vstack([groove_l, arc, groove_r])
    i0 = len(groove_l)
    i1 = i0 + n_arc - 1
    return pts, i0, i1, g


def profile_normals(P):
    d = np.zeros_like(P)
    d[1:-1] = P[2:] - P[:-2]
    d[0] = P[1] - P[0]
    d[-1] = P[-1] - P[-2]
    n = np.stack([d[:, 1], -d[:, 0]], 1)
    n /= np.linalg.norm(n, axis=1, keepdims=True)
    return n


def band_profile(zmm):
    h = np.zeros_like(zmm)
    for zc, bw in BANDS:
        t = np.abs(zmm - zc) / (bw / 2)
        h = np.maximum(h, np.where(t < 1, np.sqrt(np.clip(1 - t ** 3.0, 0, 1)), 0))
    return h


def build_spine(name, T, rb, mat):
    P, i0, i1, g = spine_profile(T, rb)
    N = profile_normals(P)
    nu = len(P)
    seg = np.linalg.norm(np.diff(P, axis=0), axis=1)
    s = np.concatenate([[0], np.cumsum(seg)])
    L_arc = s[i1] - s[i0]
    u_img = (s - s[i0]) / L_arc
    # weight of band displacement across the profile (full on arc, fading in the groove)
    w = np.ones(nu)
    for i in range(nu):
        if i < i0:
            w[i] = max(0.0, 1 - (s[i0] - s[i]) / (1.8 * MM))
        elif i > i1:
            w[i] = max(0.0, 1 - (s[i] - s[i1]) / (1.8 * MM))
    w = w ** 1.5
    Hmm = H_BOOK / MM
    zs = set(np.round(np.arange(0, Hmm + 1e-6, 1.0), 3))
    for zc, bw in BANDS:
        zs |= set(np.round(np.arange(zc - bw / 2 - 1.5, zc + bw / 2 + 1.5, 0.22), 3))
    zs |= set(np.round(np.arange(0, 3.0, 0.15), 3)) | set(np.round(np.arange(Hmm - 5.0, Hmm, 0.15), 3))
    zs.add(round(Hmm, 3))
    zmm = np.array(sorted(z for z in zs if 0 <= z <= Hmm))
    nv = len(zmm)
    bp = band_profile(zmm)
    r_end = 1.3
    dz_end = np.minimum(zmm, Hmm - zmm)
    inset = np.where(dz_end < r_end, r_end - np.sqrt(np.clip(r_end ** 2 - (r_end - dz_end) ** 2, 0, None)), 0) * MM
    headcap = 0.45 * MM * np.exp(-((Hmm - zmm - 3.0) / 1.6) ** 2) + 0.25 * MM * np.exp(-((zmm - 2.5) / 1.4) ** 2)
    # outer surface
    disp = (BAND_H * bp[:, None] + headcap[:, None]) * w[None, :] - inset[:, None]
    ox = P[None, :, 0] + N[None, :, 0] * disp
    oy = P[None, :, 1] + N[None, :, 1] * disp
    oz = np.repeat(zmm[:, None] * MM, nu, 1)
    # inner surface (leather + lining thickness)
    ix = np.repeat((P[:, 0] - N[:, 0] * LEATHER_T)[None, :], nv, 0)
    iy = np.repeat((P[:, 1] - N[:, 1] * LEATHER_T)[None, :], nv, 0)
    outer = np.stack([ox, oy, oz], -1).reshape(-1, 3)
    inner = np.stack([ix, iy, oz], -1).reshape(-1, 3)
    verts = np.vstack([outer, inner])
    off = nv * nu
    idx = lambda iv, iu: iv * nu + iu
    faces = []
    for iv in range(nv - 1):
        for iu in range(nu - 1):
            a, b, c, d = idx(iv, iu), idx(iv, iu + 1), idx(iv + 1, iu + 1), idx(iv + 1, iu)
            faces.append((a, b, c, d))
            faces.append((off + a, off + d, off + c, off + b))
    top, bot = nv - 1, 0
    for iu in range(nu - 1):
        faces.append((idx(top, iu), idx(top, iu + 1), off + idx(top, iu + 1), off + idx(top, iu)))
        faces.append((idx(bot, iu), off + idx(bot, iu), off + idx(bot, iu + 1), idx(bot, iu + 1)))
    for iv in range(nv - 1):
        faces.append((idx(iv, 0), idx(iv + 1, 0), off + idx(iv + 1, 0), off + idx(iv, 0)))
        faces.append((idx(iv, nu - 1), off + idx(iv, nu - 1), off + idx(iv + 1, nu - 1), idx(iv + 1, nu - 1)))
    uv_outer = np.stack([np.repeat(u_img[None, :], nv, 0), np.repeat((zmm / Hmm)[:, None], nu, 1)], -1).reshape(-1, 2)
    uv_inner = np.full((off, 2), -1.0)
    uvs = np.vstack([uv_outer, uv_inner])
    ob = mesh_obj(name, verts, faces, uvs=uvs, smooth=True, mat=mat)
    return ob, L_arc, g


def build_pageblock(name, T, rb, g, mat):
    hw = T / 2
    hx = hw - BOARD
    R = (hw * hw + rb * rb) / (2 * rb)
    y_end = D_BOOK - rb
    xs = np.linspace(-hx, hx, 24)
    back = -(np.sqrt(R * R - xs * xs) - (R - rb)) + LEATHER_T + 0.15 * MM
    conc = min(rb * 0.9, 3.5 * MM)
    xf = xs[::-1]
    front = y_end - OVERHANG - conc * (1 - (xf / hx) ** 2)
    poly = [(x, y) for x, y in zip(xs, back)] + [(x, y) for x, y in zip(xf, front)]
    bm = bmesh.new()
    vb = [bm.verts.new((x, y, OVERHANG)) for x, y in poly]
    fb = bm.faces.new(vb)
    ext = bmesh.ops.extrude_face_region(bm, geom=[fb])
    vt = [e for e in ext['geom'] if isinstance(e, bmesh.types.BMVert)]
    bmesh.ops.translate(bm, verts=vt, vec=(0, 0, H_BOOK - 2 * OVERHANG))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    bmesh.ops.triangulate(bm, faces=[f for f in bm.faces if len(f.verts) > 4])
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    ob = bpy.data.objects.new(name, me)
    link(ob)
    ob.data.materials.append(mat)
    m = ob.modifiers.new('bevel', 'BEVEL'); m.width = 0.35 * MM; m.segments = 2; m.limit_method = 'ANGLE'
    return ob


def build_headband(name, T, rb, mat):
    hw = T / 2
    hx = hw - BOARD - 0.3 * MM
    R = (hw * hw + rb * rb) / (2 * rb)
    xs = np.linspace(-hx, hx, 30)
    ys = -(np.sqrt(R * R - xs * xs) - (R - rb)) + LEATHER_T + 1.0 * MM
    r = 0.95 * MM
    zc = H_BOOK - OVERHANG + 0.6 * MM
    nring = 10
    verts, faces = [], []
    for i, (x, y) in enumerate(zip(xs, ys)):
        for k in range(nring):
            a = 2 * math.pi * k / nring
            verts.append((x, y + r * math.cos(a), zc + r * math.sin(a)))
    for i in range(len(xs) - 1):
        for k in range(nring):
            a, b = i * nring + k, i * nring + (k + 1) % nring
            faces.append((a, b, b + nring, a + nring))
    return mesh_obj(name, verts, faces, smooth=True, mat=mat)


