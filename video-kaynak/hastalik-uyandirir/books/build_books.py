def mesh_obj(name, verts, faces, uvs=None, smooth=True, mat=None):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in verts], [], [tuple(f) for f in faces])
    if uvs is not None:
        uvl = me.uv_layers.new(name='UVMap')
        # uvs: per-vertex array -> per-loop
        lv = np.zeros(len(me.loops), dtype=np.int64)
        me.loops.foreach_get('vertex_index', lv)
        uv_loop = np.asarray(uvs, dtype=np.float32)[lv]
        uvl.data.foreach_set('uv', uv_loop.ravel())
    me.validate()
    me.update()
    if smooth:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    if mat is not None:
        ob.data.materials.append(mat)
    return link(ob)


def box_obj(name, x0, x1, y0, y1, z0, z1, mat=None, bevel=0.0, segs=2, uv_scale=1.8, uv_off=(0.0, 0.0)):
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
         (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    f = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    me = bpy.data.meshes.new(name)
    me.from_pydata(v, [], f)
    me.update()
    uvl = me.uv_layers.new(name='UVMap')
    for poly in me.polygons:
        nx, ny, nz = (abs(c) for c in poly.normal)
        for li in poly.loop_indices:
            co = me.vertices[me.loops[li].vertex_index].co
            if nz >= nx and nz >= ny:
                uv = (co.x, co.y)
            elif ny >= nx:
                uv = (co.x, co.z)
            else:
                uv = (co.y, co.z)
            uvl.data[li].uv = (uv[0] / uv_scale + uv_off[0], uv[1] / uv_scale + uv_off[1])
    ob = bpy.data.objects.new(name, me)
    link(ob)
    if mat is not None:
        ob.data.materials.append(mat)
    if bevel > 0:
        m = ob.modifiers.new('bevel', 'BEVEL')
        m.width = bevel
        m.segments = segs
        m.limit_method = 'ANGLE'
        m.harden_normals = True
        ob.data.shade_smooth()
    return ob


