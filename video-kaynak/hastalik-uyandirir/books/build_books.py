def velvet_cloth():
    """Velvet runner on the plinth, rolling over its front edge and hanging with soft folds."""
    W2 = PL_W / 2 + 0.03
    nx, nt = 120, 70
    y_front = PL_Y0
    top_len = PL_Y1 - PL_Y0 - 0.01
    hang = max(PLINTH_H - 0.008, 0.01)
    roll = 0.010
    L = top_len + roll + hang
    verts, faces = [], []
    for j in range(nt + 1):
        t = j / nt * L
        for i in range(nx + 1):
            x = -W2 + 2 * W2 * i / nx
            fx = 0.5 + 0.5 * math.sin(x * 41 + 1.3 + 0.8 * math.sin(x * 11.0))
            if t <= top_len:
                y = y_front + top_len - t
                z = PLINTH_H + 0.0006 + 0.0007 * math.sin(x * 57 + 0.7) * math.sin(t * 31) * (t / top_len)
            elif t <= top_len + roll:
                a = (t - top_len) / roll * (math.pi / 2)
                rr = 0.005 + 0.003 * fx
                y = y_front - rr * math.sin(a)
                z = PLINTH_H + 0.0006 - rr * (1 - math.cos(a))
            else:
                h = t - top_len - roll
                rr = 0.005 + 0.003 * fx
                amp = 0.010 * (h / hang) ** 1.2
                y = y_front - rr - amp * fx
                z = max(PLINTH_H + 0.0006 - rr - h, 0.0012)
            if abs(x) > PL_W / 2:
                d = abs(x) - PL_W / 2
                z -= d * 0.8
            verts.append((x, y, z))
    for j in range(nt):
        for i in range(nx):
            a_ = j * (nx + 1) + i
            faces.append((a_, a_ + nx + 1, a_ + nx + 2, a_ + 1))
    ob = mesh_obj('velvet', verts, faces, smooth=True, mat=velvet)
    so = ob.modifiers.new('solid', 'SOLIDIFY'); so.thickness = VELVET_T; so.offset = -1
    return ob
