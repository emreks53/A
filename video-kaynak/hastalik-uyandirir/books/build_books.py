    t.l(nm.outputs[0], bsdf.inputs['Normal'])
    bsdf.inputs['Coat Weight'].default_value = coat
    bsdf.inputs['Coat Roughness'].default_value = 0.22
    t.l(bsdf.outputs[0], out.inputs['Surface'])
    return mat


