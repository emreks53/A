def footprint(cx, cy, rot, T, depth=D_BOOK):
    """Rectangle footprint (shoulder line -> back) in world XY."""
    hw = T / 2
    pts = np.array([[-hw, 0.0], [hw, 0.0], [hw, depth - 0.006], [-hw, depth - 0.006]])
    c, s = math.cos(rot), math.sin(rot)
    M = np.array([[c, -s], [s, c]])
    return pts @ M.T + np.array([cx, cy])


def sat_overlap(A, B):
    for poly in (A, B):
        for k in range(4):
            e = poly[(k + 1) % 4] - poly[k]
            n = np.array([-e[1], e[0]])
            pa, pb = A @ n, B @ n
            if pa.max() < pb.min() or pb.max() < pa.min():
                return False
    return True


