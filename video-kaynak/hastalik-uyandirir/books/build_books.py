    t.l(dif.outputs['Color'], hsv.inputs['Color'])
    rr = t.n('ShaderNodeMapRange'); t.l(rough.outputs['Color'], rr.inputs['Value'])
    rr.inputs['To Min'].default_value = rough_lo; rr.inputs['To Max'].default_value = rough_hi
    nm = t.n('ShaderNodeNormalMap'); nm.inputs['Strength'].default_value = 0.6
    t.l(nor.outputs['Color'], nm.inputs['Color'])
    bsdf = t.n('ShaderNodeBsdfPrincipled')
    col = hsv.outputs[0]
    rough_o = rr.outputs['Result']
    if dust > 0:
        dn = t.n('ShaderNodeTexNoise'); dn.inputs['Scale'].default_value = 2600.0; dn.inputs['Detail'].default_value = 1.0
