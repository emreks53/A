class Sheet:
    def __init__(self, name, w, h, ppm, x0):
        self.name, self.w, self.h, self.ppm, self.x0 = name, w, h, ppm, x0
        self.col = bpy.data.collections.new("sheet_" + name)
        bpy.context.scene.collection.children.link(self.col)


_DS = {}


def _ds_mat(v=1.0):
    key = round(v, 4)
    if key in _DS:
        return _DS[key]
    m = bpy.data.materials.new("em%.3f" % v)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    o = nt.nodes.new("ShaderNodeOutputMaterial")
    e = nt.nodes.new("ShaderNodeEmission")
    e.inputs["Color"].default_value = (v, v, v, 1)
    e.inputs["Strength"].default_value = 1.0
    nt.links.new(e.outputs[0], o.inputs[0])
    _DS[key] = m
    return m


class Painter:
    """Draws white shapes on a sheet (z=0 plane, offset by sheet.x0)."""

    def __init__(self, sheet, fonts):
        self.s = sheet
        self.f = fonts
        self._cap = {}

    def _link(self, ob, v=1.0, z=0.0):
        self.s.col.objects.link(ob)
        ob.location.x += self.s.x0
        ob.location.z = z
        if ob.data and hasattr(ob.data, "materials"):
            ob.data.materials.append(_ds_mat(v))
        return ob

    # ---------------------------------------------------------------- text
    def cap_ratio(self, font):
        if font in self._cap:
            return self._cap[font]
        cu = bpy.data.curves.new("capH", "FONT")
        cu.body = "H"
        cu.font = self.f[font]
        cu.size = 1.0
        ob = bpy.data.objects.new("capH", cu)
        bpy.context.scene.collection.objects.link(ob)
        bpy.context.view_layer.update()
        r = ob.dimensions.y
        bpy.data.objects.remove(ob)
        self._cap[font] = r
        return r

    def text(self, body, font, cap, x, y, spacing=1.0, align="CENTER", max_w=None, v=1.0):
        """Single line; (x, y) = baseline anchor; cap = cap height (m)."""
        size = cap / self.cap_ratio(font)
        cu = bpy.data.curves.new("txt", "FONT")
        cu.body = body
        cu.font = self.f[font]
        cu.size = size
        cu.align_x = align
        cu.align_y = "BOTTOM_BASELINE"
        cu.space_character = spacing
        ob = bpy.data.objects.new("txt", cu)
        ob.location = (x, y, 0)
        self._link(ob, v)
        if max_w:
            bpy.context.view_layer.update()
            if ob.dimensions.x > max_w:
                k = max_w / ob.dimensions.x
                ob.scale = (k, max(k, 0.82), 1)
        return ob

    def textbox(self, body, font, size, x, y_top, w, h, line=1.0, align="JUSTIFY", v=1.0):
        cu = bpy.data.curves.new("box", "FONT")
        cu.body = body
        cu.font = self.f[font]
        cu.size = size
        cu.align_x = align
        cu.align_y = "TOP_BASELINE"
        cu.space_line = line
        cu.overflow = "TRUNCATE"
        tb = cu.text_boxes[0]
        tb.x, tb.y = 0.0, 0.0
        tb.width, tb.height = w, h
        ob = bpy.data.objects.new("box", cu)
        ob.location = (x, y_top, 0)
        return self._link(ob, v)

    # ---------------------------------------------------------------- shapes
    def poly(self, pts, v=1.0, z=0.0):
        """Filled closed polygon (list of (x,y)). Several rings -> even-odd holes."""
        rings = pts if isinstance(pts[0][0], (list, tuple)) else [pts]
        cu = bpy.data.curves.new("poly", "CURVE")
        cu.dimensions = "2D"
        cu.fill_mode = "BOTH"
        for ring in rings:
            sp = cu.splines.new("POLY")
            sp.points.add(len(ring) - 1)
            for i, (x, y) in enumerate(ring):
                sp.points[i].co = (x, y, 0, 1)
            sp.use_cyclic_u = True
        return self._link(bpy.data.objects.new("poly", cu), v, z)

    def stroke(self, pts, width, v=1.0, closed=False, z=0.0):
        """Polyline stroke of constant width (built as a filled ribbon polygon with round-ish caps)."""
        if len(pts) < 2:
            return None
        hw = width / 2
        left, right = [], []
        n = len(pts)
        for i in range(n):
            if closed:
                a = Vector(pts[i - 1]); b = Vector(pts[(i + 1) % n])
            else:
                a = Vector(pts[max(0, i - 1)]); b = Vector(pts[min(n - 1, i + 1)])
            d = (b - a)
            if d.length < 1e-12:
                d = Vector((1, 0))
            d.normalize()
            nrm = Vector((-d.y, d.x))
            p = Vector(pts[i])
            left.append(tuple(p + nrm * hw)); right.append(tuple(p - nrm * hw))
        if closed:
            return self.poly([left, right], v, z)          # even-odd ring
        return self.poly(left + right[::-1], v, z)

    def rect(self, x0, y0, x1, y1, v=1.0, z=0.0):
        return self.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], v, z)

    def frame(self, x0, y0, x1, y1, lw, v=1.0):
        return self.poly([[(x0, y0), (x1, y0), (x1, y1), (x0, y1)],
                          [(x0 + lw, y0 + lw), (x1 - lw, y0 + lw), (x1 - lw, y1 - lw), (x0 + lw, y1 - lw)]], v)

    def disc(self, x, y, r, n=20, v=1.0):
        return self.poly([(x + r * math.cos(2 * math.pi * i / n), y + r * math.sin(2 * math.pi * i / n)) for i in range(n)], v)

    def lozenge(self, x, y, rx, ry, v=1.0):
        return self.poly([(x + rx, y), (x, y + ry), (x - rx, y), (x, y - ry)], v)


# ------------------------------------------------------------------ ornament geometry (2D, pure python)

def _bez(p0, p1, p2, p3, n=16):
    out = []
    for i in range(n + 1):
        t = i / n
        a = (1 - t) ** 3; b = 3 * (1 - t) ** 2 * t; c = 3 * (1 - t) * t ** 2; d = t ** 3
        out.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))
    return out


def _xf(pts, ox=0.0, oy=0.0, s=1.0, rot=0.0, mx=1.0, my=1.0):
    c, si = math.cos(rot), math.sin(rot)
    out = []
    for x, y in pts:
        x, y = x * mx * s, y * my * s
        out.append((ox + x * c - y * si, oy + x * si + y * c))
    return out


def leaf_shape(length, width, curl=0.0, n=14):
    """Pointed leaf / rumi blade along +x from origin; curl bends the tip (radians)."""
    up, dn = [], []
    for i in range(n + 1):
        t = i / n
        w = width * math.sin(math.pi * t) ** 0.85 * (1 - 0.35 * t)
        ang = curl * t * t
        x = length * t * math.cos(ang)
        y = length * t * math.sin(ang)
        nx, ny = -math.sin(ang), math.cos(ang)
        up.append((x + nx * w * 0.5, y + ny * w * 0.5))
        dn.append((x - nx * w * 0.5, y - ny * w * 0.5))
    return up + dn[::-1][1:-1]


def spiral_pts(cx, cy, r0, r1, turns, a0=0.0, n=60, cw=False):
    out = []
    for i in range(n + 1):
        t = i / n
        a = a0 + (-1 if cw else 1) * 2 * math.pi * turns * t
        r = r0 + (r1 - r0) * t
        out.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return out


def rumi_blade(cx, cy, R, a0, sweep, w, n=28, shrink=0.42):
    """Rumi (split-leaf) blade: a tapering crescent following an inward spiral."""
    up, dn = [], []
    for i in range(n + 1):
        t = i / n
        a = a0 + sweep * t
        r = R * (1 - shrink * t)
        ww = w * (math.sin(math.pi * min(1.0, 0.08 + t * 1.02)) ** 0.65) * (1 - 0.55 * t)
        up.append((cx + (r + ww / 2) * math.cos(a), cy + (r + ww / 2) * math.sin(a)))
        dn.append((cx + (r - ww / 2) * math.cos(a), cy + (r - ww / 2) * math.sin(a)))
    return up + dn[::-1]


def _scaled(ring, k, ox=0.0, oy=0.0):
    return [(ox + (x - ox) * k, oy + (y - oy) * k) for x, y in ring]


def corner_ornament(P, cx, cy, L, sx, sy, lw):
    """Ottoman corner piece (kosebent): a filled, scalloped quarter-medallion pointing along the
    diagonal, with a double contour and tooled negative-space palmette / rumi blades."""
    N = 160
    ring = [(0.0, 0.0)]
    for i in range(N + 1):
        th = (math.pi / 2) * i / N
        u = abs(th - math.pi / 4) / (math.pi / 4)
        r = L * (1.0 - 0.40 * u ** 0.85)
        r *= 1 + 0.045 * math.cos(10 * (th - math.pi / 4))
        ring.append((r * math.cos(th), r * math.sin(th)))
    X = lambda pts: _xf(pts, cx, cy, 1, 0, sx, sy)
    P.poly(X(ring), v=1.0, z=0.000)
    P.poly(X(_scaled(ring, 0.915)), v=0.0, z=0.001)
    P.poly(X(_scaled(ring, 0.870)), v=1.0, z=0.002)
    d = math.pi / 4
    # negative tooling (z above)
    pal = leaf_shape(L * 0.40, L * 0.17, 0.0)
    P.poly(X(_xf(pal, L * 0.16 * math.cos(d), L * 0.16 * math.sin(d), 1, d)), v=0.0, z=0.003)
    for side in (-1, 1):
        bl = rumi_blade(L * 0.20 * math.cos(d), L * 0.20 * math.sin(d), L * 0.30, d + side * 0.25,
                        side * 1.9, L * 0.085)
        P.poly(X(bl), v=0.0, z=0.003)
        bl2 = rumi_blade(L * 0.06 * math.cos(d + side * 0.6), L * 0.06 * math.sin(d + side * 0.6), L * 0.48,
                         d + side * 0.95, side * 0.55, L * 0.05, shrink=0.15)
        P.poly(X(bl2), v=0.0, z=0.003)
    P.poly(X([(L * 0.02, L * 0.02), (L * 0.13, L * 0.02), (L * 0.02, L * 0.13)]), v=0.0, z=0.003)
    for k in (0.62, 0.78):
        P.disc(*X([(L * k * math.cos(d), L * k * math.sin(d))])[0], L * 0.028, v=0.0).location.z = 0.003
    # outer hairline contour
    P.stroke(X([(x * 1.07, y * 1.07) for x, y in ring[1:]]), lw * 0.7, z=0.0)


def flourish(P, cx, cy, width, lw, small=False):
    """Horizontal rule ornament: tapered lines, central lozenge with dots, small curls."""
    hw = width / 2
    for s in (-1, 1):
        pts = [(cx + s * (0.006 if not small else 0.004), cy), (cx + s * hw, cy)]
        # tapered wedge
        x0, x1 = pts[0][0], pts[1][0]
        P.poly([(x0, cy - lw * 0.9), (x1, cy - lw * 0.15), (x1, cy + lw * 0.15), (x0, cy + lw * 0.9)])
        if not small:
            sp = spiral_pts(cx + s * (hw * 0.55), cy + 0.0016, 0.0016, 0.0003, 0.9, a0=-math.pi / 2, cw=(s < 0))
            P.stroke(sp, lw * 0.7)
            sp = spiral_pts(cx + s * (hw * 0.55), cy - 0.0016, 0.0016, 0.0003, 0.9, a0=math.pi / 2, cw=(s > 0))
            P.stroke(sp, lw * 0.7)
        P.disc(cx + s * (hw + lw * 1.4), cy, lw * 1.1)
    P.lozenge(cx, cy, 0.0042 if not small else 0.0028, 0.0019 if not small else 0.0013)
    P.disc(cx, cy, 0.0006 if not small else 0.0004, v=0.0)


def rosette(P, cx, cy, r, petals=8, lw=0.0004):
    for k in range(petals):
        a = 2 * math.pi * k / petals + math.pi / petals
        P.poly(_xf(leaf_shape(r, r * 0.42, 0.0), cx, cy, 1, a))
    P.disc(cx, cy, r * 0.22, v=0.0)
    P.disc(cx, cy, r * 0.12)


def semse(P, cx, cy, rx, ry, lw):
    """Small almond medallion (semse): scalloped filled outline, double contour, negative palmettes,
    pendants (salbek) above and below."""
    N = 200
    ring = []
    for i in range(N):
        t = 2 * math.pi * i / N
        rr = 1 + 0.045 * math.cos(18 * t)
        sx = math.sin(t)
        sy = math.cos(t)
        sy = math.copysign(abs(sy) ** 0.9, sy)
        ring.append((cx + rx * rr * sx, cy + ry * rr * sy))
    P.poly(ring, v=1.0, z=0.000)
    P.poly(_scaled(ring, 0.90, cx, cy), v=0.0, z=0.001)
    P.poly(_scaled(ring, 0.85, cx, cy), v=1.0, z=0.002)
    for s in (-1, 1):
        P.poly(_xf(leaf_shape(ry * 0.66, rx * 0.40, 0.0), cx, cy, 1, s * math.pi / 2), v=0.0, z=0.003)
        for side in (-1, 1):
            bl = rumi_blade(cx, cy + s * ry * 0.05, ry * 0.52, s * math.pi / 2 + side * 0.32, side * s * 1.7,
                            rx * 0.20)
            P.poly(bl, v=0.0, z=0.003)
        P.lozenge(cx, cy + s * (ry * 1.08 + 0.0030), 0.0011, 0.0026)
        P.disc(cx, cy + s * (ry * 1.08 + 0.0068), 0.0007)
    P.disc(cx, cy, rx * 0.16, v=0.0).location.z = 0.004
    P.disc(cx, cy, rx * 0.08, v=1.0).location.z = 0.005
    P.stroke(_scaled(ring, 1.075, cx, cy), lw * 0.7, closed=True)


def draw_cover(P, title=True):
    """Front board (joint at x=0, fore-edge at x=BK_WF)."""
    W, H = BK_WF, BK_H
    lw = 0.0006
    x0, x1, y0, y1 = 0.0105, W - 0.0068, 0.0068, H - 0.0068
    P.frame(x0, y0, x1, y1, lw)
    # inner border band: two rules with a chain of small lozenges
    g = 0.0032
    P.frame(x0 + g, y0 + g, x1 - g, y1 - g, lw * 0.6)
    band = 0.0036
    P.frame(x0 + g + band, y0 + g + band, x1 - g - band, y1 - g - band, lw * 0.6)
    mid = g + band / 2
    step = 0.0042
    for (ax, ay, bx, by) in [(x0 + mid, y0 + mid, x1 - mid, y0 + mid), (x0 + mid, y1 - mid, x1 - mid, y1 - mid),
                             (x0 + mid, y0 + mid, x0 + mid, y1 - mid), (x1 - mid, y0 + mid, x1 - mid, y1 - mid)]:
        L = math.hypot(bx - ax, by - ay)
        n = int(L / step)
        for i in range(1, n):
            t = i / n
            px, py = ax + (bx - ax) * t, ay + (by - ay) * t
            if ay == by:
                P.lozenge(px, py, 0.0013, 0.0009)
            else:
                P.lozenge(px, py, 0.0009, 0.0013)
    # corner pieces
    ix0, ix1 = x0 + g + band + 0.0012, x1 - g - band - 0.0012
    iy0, iy1 = y0 + g + band + 0.0012, y1 - g - band - 0.0012
    cs = 0.027
    corner_ornament(P, ix0, iy0, cs, 1, 1, 0.00045)
    corner_ornament(P, ix1, iy0, cs, -1, 1, 0.00045)
    corner_ornament(P, ix0, iy1, cs, 1, -1, 0.00045)
    corner_ornament(P, ix1, iy1, cs, -1, -1, 0.00045)
    cx = (x0 + x1) / 2
    if title:
        P.text("RİSALE-İ NUR KÜLLİYATINDAN", "corm_bold", 0.0030, cx, 0.1755, spacing=1.22, max_w=0.105)
        flourish(P, cx, 0.1690, 0.062, 0.00045, small=True)
