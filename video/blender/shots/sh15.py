def spine_bulge(T):
    return 0.17 * T + 0.0025


def spine_arc_pts(T, n=48):
    """Outer spine arc (closed book frame, x<0 bulge) from the back joint (0,0) to the front joint (0,T).
    Returns list of (x, z, arc_len)."""
    sd = spine_bulge(T)
    pts = []
    a = 0.0
    prev = None
    for i in range(n + 1):
        t = i / n
        ang = math.pi * t
        x = -sd * math.sin(ang)
        z = T * 0.5 * (1 - math.cos(ang))
        if prev:
            a += math.hypot(x - prev[0], z - prev[1])
        pts.append((x, z, a))
        prev = (x, z)
    return pts


def spine_arc_len(T):
    return spine_arc_pts(T)[-1][2]


