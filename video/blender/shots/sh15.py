_SYL = ("bir ve bu da de ile ki her şey o ne için gibi ol an la le ra re na ne ka ke ma me ta te sa se şa şe ya ye "
        "ha he za ze ci cı çi çı dır dir tır tir lık lik muş miş sı si ğı ği an en ın in un ün ar er ır ir "
        "ra rı ri ru ro ba be bi bu ca ce cu da dı di du ga ge gi gö gü ha hi hu ka kı ki ku ko kö la lı li "
        "lu ma mı mi mu na nı ni nu ö ü ra rı sa sı si su ta tı ti tu ü ya yı yi yo yu za zı zi").split()
# Turkish words never start with "ğ" (and a lone vowel-less syllable is never a word start)
_SYL0 = [x for x in _SYL if not x.startswith("ğ")]


def pseudo_text(rng, n_words, cap_chance=0.07):
    """Turkish-looking filler (no real or fake quotation). It is only ever rendered blurred."""
    words = []
    new_sentence = True
    for i in range(n_words):
        k = rng.choice((1, 1, 2, 2, 2, 3, 3, 4))
        w = rng.choice(_SYL0) + "".join(rng.choice(_SYL) for _ in range(k - 1))
        if rng.random() < 0.12:
            w = rng.choice(("ve", "bu", "bir", "o", "ki", "her", "da", "de", "ile", "ne"))
        if new_sentence or rng.random() < cap_chance:
            w = ("İ" if w[0] == "i" else w[0].upper()) + w[1:]
            new_sentence = False
        r = rng.random()
        if r < 0.075:
            w += ","
        elif r < 0.115:
            w += "."
            new_sentence = True
        elif r < 0.12:
            w += ":"
        words.append(w)
    return " ".join(words)


def pseudo_arabic_line(P, rng, cx, yb, width, u):
    """An abstract Arabic-script line (connected baselines, teeth, alifs, loops, bowls, dots, harakat),
    centred on cx with baseline yb. Only ever rendered pre-blurred: it reads as a quoted Arabic line,
    never as text."""
    words = []
    total = 0.0
    while True:
        L = rng.uniform(1.4, 4.2) * u
        if total + L > width and words:
            break
        words.append(L)
        total += L + rng.uniform(0.55, 0.9) * u
    x = cx + total / 2                                    # written right to left
    lw = 0.12 * u
    for L in words:
        x0, x1 = x - L, x
        P.stroke([(x1, yb), (x0 + 0.2 * u, yb + rng.uniform(-0.05, 0.05) * u), (x0, yb)], lw)
        n = max(1, int(L / (0.55 * u)))
        for i in range(n):
            px = x1 - (i + 0.5) * L / n + rng.uniform(-0.1, 0.1) * u
            r = rng.random()
            if r < 0.30:      # tooth
                P.stroke([(px, yb), (px + 0.03 * u, yb + 0.55 * u)], 0.11 * u)
            elif r < 0.48:    # alif / lam
                h = rng.uniform(1.6, 2.1) * u
                P.stroke([(px, yb - 0.05 * u), (px - 0.06 * u, yb + h)], 0.14 * u)
            elif r < 0.62:    # loop (waw / mim / ha)
                rr = 0.27 * u
                P.stroke([(px + rr * math.cos(a), yb + rr + rr * math.sin(a)) for a in
                          [2 * math.pi * k / 14 for k in range(15)]], 0.10 * u)
            elif r < 0.72 and i == n - 1:   # final bowl (nun / ya)
                rr = 0.6 * u
                P.stroke([(px - rr + rr * math.cos(a), yb - rr * 0.8 * math.sin(a) + 0.02 * u) for a in
                          [math.pi * k / 12 for k in range(13)]], 0.12 * u)
            # dots
            q = rng.random()
            if q < 0.35:
                nd = rng.choice((1, 1, 2, 3))
                above = rng.random() < 0.6
                for d in range(nd):
                    P.disc(px + (d - (nd - 1) / 2) * 0.24 * u, yb + (1.0 if above else -0.55) * u + (0.22 * u if nd == 3 and d == 1 else 0), 0.075 * u, n=10)
            # harakat
            hq = rng.random()
            if hq < 0.35:
                yy = yb + (1.45 if hq < 0.25 else -0.95) * u
                P.stroke([(px - 0.22 * u, yy - 0.08 * u), (px + 0.22 * u, yy + 0.08 * u)], 0.06 * u)
            elif hq < 0.42:   # shadda-like
                yy = yb + 1.55 * u
                P.stroke([(px - 0.25 * u, yy + 0.12 * u), (px - 0.12 * u, yy), (px, yy + 0.12 * u), (px + 0.12 * u, yy),
                          (px + 0.25 * u, yy + 0.12 * u)], 0.07 * u)
        x = x0 - rng.uniform(0.55, 0.9) * u
    return total


PAGE_MARG = (0.020, 0.015, 0.020, 0.024)    # inner, outer, top, bottom
HEAD_H = 0.026                               # height of the separately rendered running-head strip
HEAD_Y = 0.0135                              # header baseline distance from the head of the page


def page_text_x(num, W):
    inner, outer, top, bottom = PAGE_MARG
    recto = num % 2 == 1
    x0 = inner if recto else outer
    x1 = W - (outer if recto else inner)
    return x0, x1


def draw_page_head(P, num, W, H):
    """Running head of one page (title, page number at the outer corner, rule). Sheet origin = page y
    H - HEAD_H. This strip is the only crisp print on a page."""
    x0, x1 = page_text_x(num, W)
    recto = num % 2 == 1
    hy = HEAD_H - HEAD_Y
    P.text("SÖZLER", "ebg_reg", 0.0023, (x0 + x1) / 2, hy, spacing=1.35)
    P.text(str(num), "ebg_med", 0.0030, x1 if recto else x0, hy, align="RIGHT" if recto else "LEFT")
    P.rect(x0, hy - 0.0030, x1, hy - 0.00265)


def line_pitch(P, font, size):
    key = (font, round(size, 6))
    if key not in P._cap:
        dims = []
        for body in ("H", "H\nH\nH"):
            cu = bpy.data.curves.new("lp", "FONT")
            cu.body = body
            cu.font = P.f[font]
            cu.size = size
            ob = bpy.data.objects.new("lp", cu)
            bpy.context.scene.collection.objects.link(ob)
            bpy.context.view_layer.update()
            dims.append(ob.dimensions.y)
            bpy.data.objects.remove(ob)
        P._cap[key] = (dims[1] - dims[0]) / 2
    return P._cap[key]


def draw_page_body(P, num, rng, W, H):
    """Body ink of one page (justified paragraphs, sometimes a centred Arabic quotation, a footnote).
    This sheet is always used pre-blurred so nothing in it is legible."""
    inner, outer, top, bottom = PAGE_MARG
    x0, x1 = page_text_x(num, W)
    tw = x1 - x0
    size = 0.0046
    pitch = line_pitch(P, "ebg_reg", size)
    has_note = rng.random() < 0.6
    bottom_body = bottom + (0.020 if has_note else 0.0)
    y0 = H - top - 0.0045                     # first baseline
    n_total = int((y0 - (bottom_body + 0.003)) / pitch) + 1
    # where the Arabic quotations go (in line slots): each takes 2 or 3 slots
    quotes = []
    n_ar = 1 if num in (720, 721) else rng.choice((0, 1, 1, 2))
    free_from = 2
    for _ in range(n_ar):
        lo, hi = free_from + 1, n_total - 6
        if hi <= lo:
            break
        at = rng.randint(lo, min(hi, lo + n_total // 2))
        nl = rng.choice((1, 1, 2))
        quotes.append((at, nl))
        free_from = at + nl + 4

    def text_block(first_slot, n_lines, indent_first):
        left = n_lines
        paras = []
        while left > 0:
            plen = min(left, rng.randint(5, 14))
            # generous word count: the box truncates the overflow, a short block would leave blank lines
            paras.append(("    " if (paras or indent_first) else "") + pseudo_text(rng, int(plen * 19)))
            left -= plen
        yb = y0 - first_slot * pitch
        P.textbox("\n".join(paras), "ebg_reg", size, x0, yb, tw, (n_lines + 0.9) * pitch, line=1.0)

    slot = 0
    for at, nl in quotes:
        if at > slot:
            text_block(slot, at - slot, slot > 0)
        # quotation: nl Arabic lines centred in (nl + 1) slots
        lead = 1.45                              # Arabic is set larger, with more leading
        span = nl * lead + 0.9
        for i in range(nl):
            yb = y0 - (at + 0.45 + 0.85 + i * lead) * pitch
            pseudo_arabic_line(P, rng, (x0 + x1) / 2, yb, tw * rng.uniform(0.55, 0.92), 0.0027)
        slot = at + span
    if slot < n_total - 0.5:
        text_block(slot, int(n_total - slot), True)
    if has_note:
        ny = bottom + 0.0185
        P.rect(x0, ny, x0 + tw * 0.28, ny + 0.0003)
        P.textbox("* " + pseudo_text(rng, 40), "ebg_reg", 0.0030, x0, ny - 0.0045, tw, 0.0165, line=1.0)


RAHLE_LEN, RAHLE_W, RAHLE_LOW = 0.50, 0.26, 0.21     # board length, width, leg length (from hinge)


def star_ring(cx, cy, ro, ri, k=8, rot=0.0):
    pts = []
    for i in range(2 * k):
        r = ro if i % 2 == 0 else ri
        a = rot + math.pi * i / k
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


RELIEF_PANELS = [(-0.128, -0.034), (0.034, 0.206)]     # board-local l ranges of the carved panels
RELIEF_YM = 0.012                                       # panel margin from the board's long edges


def relief_panel(P, x0, y0, x1, y1, s):
    """Carved panel height map (0 = board surface at the panel rim, 1 = top of the carving):
    raised frame, sunk ground, interlaced 8-point star strapwork, rosette bosses."""
    P.rect(x0 + 0.0012, y0 + 0.0012, x1 - 0.0012, y1 - 0.0012, v=0.30).location.z = 0.0005
    P.frame(x0 + 0.0012, y0 + 0.0012, x1 - 0.0012, y1 - 0.0012, 0.0062, v=1.0).location.z = 0.001
    P.frame(x0 + 0.0095, y0 + 0.0095, x1 - 0.0095, y1 - 0.0095, 0.0024, v=0.80).location.z = 0.001
    fx0, fy0, fx1, fy1 = x0 + 0.015, y0 + 0.015, x1 - 0.015, y1 - 0.015
    nx = max(1, int(round((fx1 - fx0) / s))); ny = max(1, int(round((fy1 - fy0) / s)))
    sx = (fx1 - fx0) / nx; sy = (fy1 - fy0) / ny
    r = min(sx, sy) * 0.5
    for i in range(nx):
        for j in range(ny):
            cx, cy = fx0 + (i + 0.5) * sx, fy0 + (j + 0.5) * sy
            P.stroke(star_ring(cx, cy, r * 0.97, r * 0.68, 8, 0.0), 0.0048, v=1.0, closed=True, z=0.002)
            P.stroke(star_ring(cx, cy, r * 0.50, r * 0.34, 8, math.pi / 8), 0.0030, v=0.85, closed=True, z=0.002)
            P.disc(cx, cy, r * 0.15, n=20, v=0.95).location.z = 0.002
    for i in range(nx + 1):
        for j in range(ny + 1):
            cx, cy = fx0 + i * sx, fy0 + j * sy
            P.stroke(star_ring(cx, cy, r * 0.40, r * 0.18, 4, math.pi / 4), 0.0034, v=0.95, closed=True, z=0.002)


def draw_relief(P, L, Wd):
    """Rahle carving height map for one board (x = l + RAHLE_LOW along the board, y across)."""
    P.rect(-0.01, -0.01, L + 0.01, Wd + 0.01, v=0.0, z=-0.01)
    for (l0, l1) in RELIEF_PANELS:
        relief_panel(P, l0 + RAHLE_LOW, RELIEF_YM, l1 + RAHLE_LOW, Wd - RELIEF_YM, 0.056)


