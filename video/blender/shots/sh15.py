def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def font_path(key):
    url, digest = FONTS[key]
    dest = os.path.join(C.ASSETS, "fonts", key + ".ttf")
    if os.path.exists(dest) and _sha256(dest) != digest:
        os.remove(dest)                       # stale / corrupt cache entry -> fetch again
    C._curl(url, dest)                        # raises if the download fails
    got = _sha256(dest)
    if got != digest:
        raise RuntimeError("sh15: font %s hash mismatch (%s != %s); refusing to render with a different typeface"
                           % (key, got, digest))
    return dest


