def ensure_design():
    done = os.path.join(DESIGN_DIR, "done.json")
    if os.path.exists(done):
        return DESIGN_DIR
    lock = DESIGN_DIR + ".lock"
    os.makedirs(os.path.dirname(DESIGN_DIR), exist_ok=True)
    # simple lock so parallel chunks on one machine do not all regenerate
    for _ in range(900):
        try:
            fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
            os.close(fd)
            break
        except FileExistsError:
            if os.path.exists(done):
                return DESIGN_DIR
            if time.time() - os.path.getmtime(lock) > 1200:
                os.remove(lock)
            time.sleep(2)
    try:
        if not os.path.exists(done):
            env = dict(os.environ, SH15_DESIGN="1")
            r = subprocess.run([bpy.app.binary_path, "-b", "--factory-startup", "-noaudio", "-P",
                                os.path.abspath(__file__)], env=env)
            if r.returncode != 0 or not os.path.exists(done):
                raise RuntimeError("sh15 design generation failed")
    finally:
        if os.path.exists(lock):
            os.remove(lock)
    return DESIGN_DIR


