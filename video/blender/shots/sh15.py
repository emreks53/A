class Sheet:
    def __init__(self, name, w, h, ppm, x0):
        self.name, self.w, self.h, self.ppm, self.x0 = name, w, h, ppm, x0
        self.col = bpy.data.collections.new("sheet_" + name)
        bpy.context.scene.collection.children.link(self.col)


_DS = {}


def _ds_mat(v=1.0):
    key = round(v, 4)
    if key in _DS:
        return _DS[key]
    m = bpy.data.materials.new("em%.3f" % v)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    o = nt.nodes.new("ShaderNodeOutputMaterial")
    e = nt.nodes.new("ShaderNodeEmission")
    e.inputs["Color"].default_value = (v, v, v, 1)
    e.inputs["Strength"].default_value = 1.0
    nt.links.new(e.outputs[0], o.inputs[0])
    _DS[key] = m
    return m


class Painter:
    """Draws white shapes on a sheet (z=0 plane, offset by sheet.x0)."""

    def __init__(self, sheet, fonts):
        self.s = sheet
        self.f = fonts
        self._cap = {}

    def _link(self, ob, v=1.0, z=0.0):
        self.s.col.objects.link(ob)
        ob.location.x += self.s.x0
        ob.location.z = z
        if ob.data and hasattr(ob.data, "materials"):
            ob.data.materials.append(_ds_mat(v))
        return ob

    # ---------------------------------------------------------------- text
    def cap_ratio(self, font):
        if font in self._cap:
            return self._cap[font]
        cu = bpy.data.curves.new("capH", "FONT")
        cu.body = "H"
        cu.font = self.f[font]
        cu.size = 1.0
        ob = bpy.data.objects.new("capH", cu)
        bpy.context.scene.collection.objects.link(ob)
        bpy.context.view_layer.update()
        r = ob.dimensions.y
        bpy.data.objects.remove(ob)
        self._cap[font] = r
        return r

    def text_width(self, body, font, cap, spacing=1.0):
        """Advance width (m) of a single line set at cap height `cap`."""
        cu = bpy.data.curves.new("tw", "FONT")
        cu.body = body
        cu.font = self.f[font]
        cu.size = cap / self.cap_ratio(font)
        cu.space_character = spacing
        ob = bpy.data.objects.new("tw", cu)
        bpy.context.scene.collection.objects.link(ob)
        bpy.context.view_layer.update()
        w = ob.dimensions.x
        bpy.data.objects.remove(ob)
        return w

    def text(self, body, font, cap, x, y, spacing=1.0, align="CENTER", max_w=None, v=1.0):
        """Single line; (x, y) = baseline anchor; cap = cap height (m). If max_w is given and the line is
        too wide, the cap height is reduced (uniform scale - type is never condensed)."""
        if max_w:
            w = self.text_width(body, font, cap, spacing)
            if w > max_w:
                cap *= max_w / w
        size = cap / self.cap_ratio(font)
        cu = bpy.data.curves.new("txt", "FONT")
        cu.body = body
        cu.font = self.f[font]
        cu.size = size
        cu.align_x = align
        cu.align_y = "BOTTOM_BASELINE"
        cu.space_character = spacing
        ob = bpy.data.objects.new("txt", cu)
        ob.location = (x, y, 0)
        self._link(ob, v)
        return ob

    def textbox(self, body, font, size, x, y_top, w, h, line=1.0, align="JUSTIFY", v=1.0):
        cu = bpy.data.curves.new("box", "FONT")
        cu.body = body
        cu.font = self.f[font]
        cu.size = size
        cu.align_x = align
        cu.align_y = "TOP_BASELINE"
        cu.space_line = line
        cu.overflow = "TRUNCATE"
        tb = cu.text_boxes[0]
        tb.x, tb.y = 0.0, 0.0
        tb.width, tb.height = w, h
        ob = bpy.data.objects.new("box", cu)
        ob.location = (x, y_top, 0)
        return self._link(ob, v)

    # ---------------------------------------------------------------- shapes
    def poly(self, pts, v=1.0, z=0.0):
        """Filled closed polygon (list of (x,y)). Several rings -> even-odd holes."""
        rings = pts if isinstance(pts[0][0], (list, tuple)) else [pts]
        cu = bpy.data.curves.new("poly", "CURVE")
        cu.dimensions = "2D"
        cu.fill_mode = "BOTH"
        for ring in rings:
            sp = cu.splines.new("POLY")
            sp.points.add(len(ring) - 1)
            for i, (x, y) in enumerate(ring):
                sp.points[i].co = (x, y, 0, 1)
            sp.use_cyclic_u = True
        return self._link(bpy.data.objects.new("poly", cu), v, z)

    def stroke(self, pts, width, v=1.0, closed=False, z=0.0):
        """Polyline stroke of constant width (built as a filled ribbon polygon with round-ish caps)."""
        if len(pts) < 2:
            return None
        hw = width / 2
        left, right = [], []
        n = len(pts)
        for i in range(n):
            if closed:
                a = Vector(pts[i - 1]); b = Vector(pts[(i + 1) % n])
            else:
                a = Vector(pts[max(0, i - 1)]); b = Vector(pts[min(n - 1, i + 1)])
            d = (b - a)
            if d.length < 1e-12:
                d = Vector((1, 0))
            d.normalize()
            nrm = Vector((-d.y, d.x))
            p = Vector(pts[i])
            left.append(tuple(p + nrm * hw)); right.append(tuple(p - nrm * hw))
        if closed:
            return self.poly([left, right], v, z)          # even-odd ring
        return self.poly(left + right[::-1], v, z)

    def rect(self, x0, y0, x1, y1, v=1.0, z=0.0):
        return self.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], v, z)

    def frame(self, x0, y0, x1, y1, lw, v=1.0):
        return self.poly([[(x0, y0), (x1, y0), (x1, y1), (x0, y1)],
                          [(x0 + lw, y0 + lw), (x1 - lw, y0 + lw), (x1 - lw, y1 - lw), (x0 + lw, y1 - lw)]], v)

    def disc(self, x, y, r, n=20, v=1.0):
        return self.poly([(x + r * math.cos(2 * math.pi * i / n), y + r * math.sin(2 * math.pi * i / n)) for i in range(n)], v)

    def lozenge(self, x, y, rx, ry, v=1.0):
        return self.poly([(x + rx, y), (x, y + ry), (x - rx, y), (x, y - ry)], v)


# ------------------------------------------------------------------ ornament geometry (2D, pure python)

def _bez(p0, p1, p2, p3, n=16):
    out = []
    for i in range(n + 1):
        t = i / n
        a = (1 - t) ** 3; b = 3 * (1 - t) ** 2 * t; c = 3 * (1 - t) * t ** 2; d = t ** 3
        out.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))
    return out


def _xf(pts, ox=0.0, oy=0.0, s=1.0, rot=0.0, mx=1.0, my=1.0):
    c, si = math.cos(rot), math.sin(rot)
    out = []
    for x, y in pts:
        x, y = x * mx * s, y * my * s
        out.append((ox + x * c - y * si, oy + x * si + y * c))
    return out


def leaf_shape(length, width, curl=0.0, n=14):
    """Pointed leaf / rumi blade along +x from origin; curl bends the tip (radians)."""
    up, dn = [], []
    for i in range(n + 1):
        t = i / n
        w = width * math.sin(math.pi * t) ** 0.85 * (1 - 0.35 * t)
        ang = curl * t * t
        x = length * t * math.cos(ang)
        y = length * t * math.sin(ang)
        nx, ny = -math.sin(ang), math.cos(ang)
        up.append((x + nx * w * 0.5, y + ny * w * 0.5))
        dn.append((x - nx * w * 0.5, y - ny * w * 0.5))
    return up + dn[::-1][1:-1]


def spiral_pts(cx, cy, r0, r1, turns, a0=0.0, n=60, cw=False):
    out = []
    for i in range(n + 1):
        t = i / n
        a = a0 + (-1 if cw else 1) * 2 * math.pi * turns * t
        r = r0 + (r1 - r0) * t
        out.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return out


def rumi_blade(cx, cy, R, a0, sweep, w, n=28, shrink=0.42):
    """Rumi (split-leaf) blade: a tapering crescent following an inward spiral."""
    up, dn = [], []
    for i in range(n + 1):
        t = i / n
        a = a0 + sweep * t
        r = R * (1 - shrink * t)
        ww = w * (math.sin(math.pi * min(1.0, 0.08 + t * 1.02)) ** 0.65) * (1 - 0.55 * t)
        up.append((cx + (r + ww / 2) * math.cos(a), cy + (r + ww / 2) * math.sin(a)))
        dn.append((cx + (r - ww / 2) * math.cos(a), cy + (r - ww / 2) * math.sin(a)))
    return up + dn[::-1]


def _scaled(ring, k, ox=0.0, oy=0.0):
    return [(ox + (x - ox) * k, oy + (y - oy) * k) for x, y in ring]


def corner_ornament(P, cx, cy, L, sx, sy, lw):
    """Gold-tooled corner fan: radiating petals with tooled mid-ribs, a quarter boss, an enclosing
    arc with pearl dots (a classic Ottoman/European binding corner)."""
    X = lambda pts: _xf(pts, cx, cy, 1, 0, sx, sy)
    lens = [0.60, 0.80, 0.98, 0.80, 0.60]
    for k in range(5):
        a = math.radians(90 * (k + 0.5) / 5)
        ln = L * lens[k]
        pet = leaf_shape(ln * 0.80, L * (0.15 if k != 2 else 0.17), 0.0)
        o = L * 0.17
        P.poly(X(_xf(pet, o * math.cos(a), o * math.sin(a), 1, a)), v=1.0, z=0.000)
        rib = [(o * math.cos(a) + t * ln * 0.62 * math.cos(a), o * math.sin(a) + t * ln * 0.62 * math.sin(a)) for t in (0.18, 1.0)]
        P.stroke(X(rib), lw * 0.45, v=0.0, z=0.001)
        if k < 4:
            b = math.radians(90 * (k + 1) / 5)
            P.disc(*X([(L * 0.70 * math.cos(b), L * 0.70 * math.sin(b))])[0], L * 0.028)
    quarter = [(0, 0)] + [(L * 0.13 * math.cos(math.radians(t)), L * 0.13 * math.sin(math.radians(t))) for t in range(0, 91, 5)]
    P.poly(X(quarter), v=1.0, z=0.0)
    arc = [(L * 1.02 * math.cos(math.radians(t)), L * 1.02 * math.sin(math.radians(t))) for t in range(6, 85, 2)]
    P.stroke(X(arc), lw * 0.8)
    for t in (14, 30, 45, 60, 76):
        P.disc(*X([(L * 1.10 * math.cos(math.radians(t)), L * 1.10 * math.sin(math.radians(t)))])[0], L * 0.022)


def flourish(P, cx, cy, width, lw, small=False):
    """Horizontal rule ornament: tapered lines, central lozenge with dots, small curls."""
    hw = width / 2
    for s in (-1, 1):
        pts = [(cx + s * (0.006 if not small else 0.004), cy), (cx + s * hw, cy)]
        # tapered wedge
        x0, x1 = pts[0][0], pts[1][0]
        P.poly([(x0, cy - lw * 0.9), (x1, cy - lw * 0.15), (x1, cy + lw * 0.15), (x0, cy + lw * 0.9)])
        if not small:
            sp = spiral_pts(cx + s * (hw * 0.55), cy + 0.0016, 0.0016, 0.0003, 0.9, a0=-math.pi / 2, cw=(s < 0))
            P.stroke(sp, lw * 0.7)
            sp = spiral_pts(cx + s * (hw * 0.55), cy - 0.0016, 0.0016, 0.0003, 0.9, a0=math.pi / 2, cw=(s > 0))
            P.stroke(sp, lw * 0.7)
        P.disc(cx + s * (hw + lw * 1.4), cy, lw * 1.1)
    P.lozenge(cx, cy, 0.0042 if not small else 0.0028, 0.0019 if not small else 0.0013)
    P.disc(cx, cy, 0.0006 if not small else 0.0004, v=0.0).location.z = 0.004


def rosette(P, cx, cy, r, petals=8, lw=0.0004):
    for k in range(petals):
        a = 2 * math.pi * k / petals + math.pi / petals
        P.poly(_xf(leaf_shape(r, r * 0.42, 0.0), cx, cy, 1, a))
    P.disc(cx, cy, r * 0.22, v=0.0).location.z = 0.004
    P.disc(cx, cy, r * 0.12).location.z = 0.005


def semse(P, cx, cy, rx, ry, lw):
    """Small almond medallion: double contour, central rosette, leaves on the axis, pendants."""
    N = 160
    ring = []
    for i in range(N):
        t = 2 * math.pi * i / N
        sy = math.cos(t)
        sy = math.copysign(abs(sy) ** 0.85, sy)
        ring.append((cx + rx * math.sin(t), cy + ry * sy))
    P.stroke(ring, lw * 1.3, closed=True)
    P.stroke(_scaled(ring, 0.86, cx, cy), lw * 0.55, closed=True)
    rosette(P, cx, cy, rx * 0.42, 8)
    for s in (-1, 1):
        P.poly(_xf(leaf_shape(ry * 0.36, rx * 0.30, 0.0), cx, cy + s * rx * 0.50, 1, s * math.pi / 2))
        P.disc(cx + s * rx * 0.58, cy, rx * 0.07)
        P.lozenge(cx, cy + s * (ry * 1.04 + 0.0028), 0.0010, 0.0024)
        P.disc(cx, cy + s * (ry * 1.04 + 0.0062), 0.0007)


def draw_cover(P, title=True, name="SÖZLER"):
    """Front board (joint at x=0, fore-edge at x=BK_WF)."""
    W, H = BK_WF, BK_H
    lw = 0.0006
    x0, x1, y0, y1 = 0.0105, W - 0.0068, 0.0068, H - 0.0068
    P.frame(x0, y0, x1, y1, lw)
    # inner border band: two rules with a chain of small lozenges
    g = 0.0032
    P.frame(x0 + g, y0 + g, x1 - g, y1 - g, lw * 0.6)
    band = 0.0036
    P.frame(x0 + g + band, y0 + g + band, x1 - g - band, y1 - g - band, lw * 0.6)
    mid = g + band / 2
    step = 0.0042
    for (ax, ay, bx, by) in [(x0 + mid, y0 + mid, x1 - mid, y0 + mid), (x0 + mid, y1 - mid, x1 - mid, y1 - mid),
                             (x0 + mid, y0 + mid, x0 + mid, y1 - mid), (x1 - mid, y0 + mid, x1 - mid, y1 - mid)]:
        L = math.hypot(bx - ax, by - ay)
        n = int(L / step)
        for i in range(1, n):
            t = i / n
            px, py = ax + (bx - ax) * t, ay + (by - ay) * t
            if ay == by:
                P.lozenge(px, py, 0.0013, 0.0009)
            else:
                P.lozenge(px, py, 0.0009, 0.0013)
    # corner pieces
    ix0, ix1 = x0 + g + band + 0.0012, x1 - g - band - 0.0012
    iy0, iy1 = y0 + g + band + 0.0012, y1 - g - band - 0.0012
    cs = 0.027
    corner_ornament(P, ix0, iy0, cs, 1, 1, 0.00045)
    corner_ornament(P, ix1, iy0, cs, -1, 1, 0.00045)
    corner_ornament(P, ix0, iy1, cs, 1, -1, 0.00045)
    corner_ornament(P, ix1, iy1, cs, -1, -1, 0.00045)
    cx = (x0 + x1) / 2
    if title:
        P.text("RİSALE-İ NUR KÜLLİYATINDAN", "corm_bold", 0.0030, cx, 0.1755, spacing=1.22, max_w=0.105)
        flourish(P, cx, 0.1690, 0.062, 0.00045, small=True)
        P.text(name, "corm_bold", 0.0128 if len(name) < 8 else 0.0112, cx, 0.1435, spacing=1.10, max_w=0.11)
        flourish(P, cx, 0.1320, 0.088, 0.0006)
        semse(P, cx, 0.0905, 0.0125, 0.0190, 0.00045)
        P.text("BEDİÜZZAMAN SAİD NURSÎ", "corm_bold", 0.0031, cx, 0.0405, spacing=1.18, max_w=0.10)
        flourish(P, cx, 0.0345, 0.040, 0.0004, small=True)
    else:
        semse(P, cx, H / 2, 0.016, 0.026, 0.00045)


def draw_spine(P, cx, title_lines, T):
    """One spine centred at cx (arc-length coords); y from tail (0) to head (BK_H)."""
    A = spine_arc_len(T)
    hw = A / 2
    lw = 0.00045
    # head & tail rolls
    for y in (0.0042, BK_H - 0.0042):
        P.rect(cx - hw * 0.92, y - lw * 0.5, cx + hw * 0.92, y + lw * 0.5)
    for y in (0.0062, BK_H - 0.0062):
        n = max(6, int(A * 0.92 / 0.0022))
        for i in range(n):
            x = cx - hw * 0.88 + (2 * hw * 0.88) * (i + 0.5) / n
            P.lozenge(x, y, 0.0006, 0.0006)
    # hub outlines (double rules each side + dotted crest)
    for hy in HUBS:
        for s in (-1, 1):
            y = hy + s * (HUB_W / 2 + 0.0011)
            P.rect(cx - hw * 0.96, y - lw * 0.5, cx + hw * 0.96, y + lw * 0.5)
            y2 = hy + s * (HUB_W / 2 + 0.0024)
            P.rect(cx - hw * 0.96, y2 - lw * 0.35, cx + hw * 0.96, y2 + lw * 0.35)
        n = max(5, int(A * 0.9 / 0.0026))
        for i in range(n):
            x = cx - hw * 0.86 + (2 * hw * 0.86) * (i + 0.5) / n
            P.disc(x, hy, 0.00045, n=10)
    panels = [(0.0085, HUBS[0] - HUB_W / 2 - 0.0035)] + \
             [(HUBS[i] + HUB_W / 2 + 0.0035, HUBS[i + 1] - HUB_W / 2 - 0.0035) for i in range(len(HUBS) - 1)] + \
             [(HUBS[-1] + HUB_W / 2 + 0.0035, BK_H - 0.0085)]
    # panel index: 0 tail, 1 author, 2 fleuron, 3 title, 4 head fleuron
    pw = min(hw * 0.86, 0.030)
    for k, (a, b) in enumerate(panels):
        if k in (1, 3):
            P.frame(cx - pw, a + 0.0010, cx + pw, b - 0.0010, lw * 0.75)
            P.frame(cx - pw + 0.0011, a + 0.0021, cx + pw - 0.0011, b - 0.0021, lw * 0.45)
    # text blocks: every line of a block shares ONE cap height, chosen so the widest line keeps
    # >= 15 % side margins in its panel and stays inside the front ~60 % of the rounded spine
    maxw = min(0.70 * 2 * pw, 0.60 * A)

    def block(lines, cap0, ym, spacing, gap=0.55):
        cap = cap0
        for ln in lines:
            w = P.text_width(ln, "corm_bold", cap0, spacing)
            cap = min(cap, cap0 * maxw / w)
        lead = cap * (1 + gap)
        n = len(lines)
        top = ym + (n * cap + (n - 1) * (lead - cap)) / 2      # cap line of the first line
        for i, ln in enumerate(lines):
            P.text(ln, "corm_bold", cap, cx, top - cap - i * lead, spacing=spacing)
        return cap
    a, b = panels[3]
    block(title_lines, 0.0052 if len(title_lines) == 1 else 0.0044, (a + b) / 2, 1.05)
    a, b = panels[1]
    block(["BEDİÜZZAMAN", "SAİD NURSÎ"], 0.0022, (a + b) / 2, 1.08, gap=0.6)
    # fleurons
    for k in (2, 4):
        a, b = panels[k]
        rosette(P, cx, (a + b) / 2, min(0.0055, (b - a) * 0.22, hw * 0.4))
    a, b = panels[0]
    block(["RİSALE-İ NUR"], 0.0018, (a + b) / 2, 1.12)


