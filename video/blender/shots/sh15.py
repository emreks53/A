def mat_leather(name, mask=None, uv_mask="uvb", foil=True, tint=1.0, seed=0.0, grain=0.0):
    """Red bonded-leather binding with hot-stamped, slightly debossed gold foil from `mask`.
    grain > 0 (hero cover only): the pebble grain also goes into albedo and roughness and the normal map is
    stronger, so it survives the denoiser (shading-only detail is smoothed away at low spp)."""
    if _simple("leather"):
        return mat_simple(name, LEATHER_RGB, 0.45)
    m, nt, out = new_mat(name)
    t = tex("leather_red_03")
    uvl = NN(nt, "ShaderNodeUVMap", uv_map="uvl")
    mp = NN(nt, "ShaderNodeMapping")
    mp.inputs["Scale"].default_value = (5.5, 5.5, 5.5)          # 1 UV unit = 1 m -> grain tile ~18 cm
    mp.inputs["Location"].default_value = (seed * 0.37, seed * 0.61, 0)
    LK(nt, uvl.outputs[0], mp.inputs["Vector"])
    col = img_node(nt, leather_coll(), vec=mp.outputs[0])
    rough = img_node(nt, t["rough"], True, vec=mp.outputs[0])
    nor = img_node(nt, t["nor"], True, vec=mp.outputs[0])
    lum = NN(nt, "ShaderNodeRGBToBW")
    LK(nt, col.outputs[0], lum.inputs[0])
    var = maprange(nt, lum.outputs[0], 0.04, 0.16, 0.78, 1.22)
    geo = NN(nt, "ShaderNodeNewGeometry")
    # large-scale tone variation (handling, dye)
    big = noise(nt, geo.outputs["Position"], 9.0, 1.0, 0.5)
    bigv = maprange(nt, big.outputs[0], 0.35, 0.65, 0.88, 1.10)
    base = mixrgb(nt, 1.0, tuple(c * tint for c in LEATHER_RGB), var, "MULTIPLY")
    base = mixrgb(nt, 1.0, base, bigv, "MULTIPLY")
    # worn edges: rubbed lighter / browner
    pt = maprange(nt, geo.outputs["Pointiness"], 0.505, 0.56, 0.0, 1.0)
    wn = noise(nt, geo.outputs["Position"], 180.0, 1.0, 0.5)
    wear = math_node(nt, "MULTIPLY", pt, maprange(nt, wn.outputs[0], 0.4, 0.62, 0.15, 1.0))
    base = mixrgb(nt, wear, base, srgb("#8E3A30"))
    LSPEC, LR0, LR1 = [float(x) for x in os.environ.get("SH15_LEATHER", "0.20,0.48,0.70").split(",")]
    r = maprange(nt, rough.outputs[0], 0.25, 0.75, LR0, LR1)
    r = math_node(nt, "ADD", r, math_node(nt, "MULTIPLY", wear, vb=0.12))
    nm = NN(nt, "ShaderNodeNormalMap")
    nm.inputs["Strength"].default_value = 0.85
    LK(nt, nor.outputs[0], nm.inputs["Color"])
    lnorm = nm.outputs[0]
    if grain > 0:
        # leather_red_03's normal map is almost flat (std 0.007) and its colour variation is clamped by
        # `var` above, so the grain never showed. One pebble is ~10 texels of the 2k maps = 0.89 mm at this
        # mapping (5.5/m) -> ~4.5 px on the cover at 112.3 s (title 80.4 mm = ~410 px). The displacement
        # map (p5-p95 0.38-0.55) drives it instead: crease darkening in albedo, glossier pebble tops, and
        # a real ~70 um pebble relief (bump) that catches the raking sun.
        disp = img_node(nt, t["disp"], True, vec=mp.outputs[0])
        pv = maprange(nt, disp.outputs[0], 0.37, 0.56, 1.0 - 0.20 * grain, 1.0 + 0.10 * grain)
        base = mixrgb(nt, 1.0, base, pv, "MULTIPLY")
        r = math_node(nt, "ADD", r, maprange(nt, disp.outputs[0], 0.37, 0.56, 0.10 * grain, -0.08 * grain))
        gb = NN(nt, "ShaderNodeBump")
        gb.inputs["Strength"].default_value = 1.0
        gb.inputs["Distance"].default_value = 0.00007 * grain
        LK(nt, disp.outputs[0], gb.inputs["Height"])
        LK(nt, nm.outputs[0], gb.inputs["Normal"])
        lnorm = gb.outputs[0]
    # satin finish: a softer, slightly warm sheen keeps sunlit crimson saturated (a strong white
    # sheen turned the lit leather salmon-pink)
    leather = principled(nt, **{"Base Color": base, "Roughness": r, "Normal": lnorm,
                                "Specular IOR Level": LSPEC, "Specular Tint": (1.0, 0.72, 0.58)})
    if not (mask and foil):
        LK(nt, leather.outputs[0], out.inputs["Surface"])
        return m
    uvm = NN(nt, "ShaderNodeUVMap", uv_map=uv_mask)
    mk = img_node(nt, mask, True, vec=uvm.outputs[0], ext="CLIP", interp="Linear")
    # foil breakup: slightly irregular edge (+-0.05: +-0.16 broke thin type differently every frame) +
    # tiny missing specks, punched only where the blurred mask is > 0.9 (inside wide foil, never in a
    # thin stroke or on a glyph edge)
    en = noise(nt, geo.outputs["Position"], 2600.0, 0.0, 0.5)
    m_e = math_node(nt, "ADD", mk.outputs[0], maprange(nt, en.outputs[0], 0.3, 0.7, -0.05, 0.05))
    foil_f = maprange(nt, m_e, 0.40, 0.62, 0.0, 1.0, interp="SMOOTHSTEP")
    mkb = img_node(nt, mask[:-4] + "_blur.png", True, vec=uvm.outputs[0], ext="CLIP", interp="Linear")
    sp = noise(nt, geo.outputs["Position"], 1400.0, 0.0, 0.5)
    holes = maprange(nt, sp.outputs[0], 0.66, 0.70, 0.0, 0.85)
    holes = math_node(nt, "MULTIPLY", holes, maprange(nt, mkb.outputs[0], 0.89, 0.91, 0.0, 1.0))
    foil_f = math_node(nt, "MULTIPLY", foil_f, math_node(nt, "SUBTRACT", va=1.0, b=holes), clamp=True)
    # deboss: foil areas pressed ~0.12 mm into the leather; grain flattened under the foil
    bump = NN(nt, "ShaderNodeBump")
    bump.invert = True
    bump.inputs["Strength"].default_value = 0.9
    bump.inputs["Distance"].default_value = 0.00012
    LK(nt, mk.outputs[0], bump.inputs["Height"])
    nmix = NN(nt, "ShaderNodeMix")
    nmix.data_type = "VECTOR"
    LK(nt, math_node(nt, "MULTIPLY", foil_f, vb=0.75), nmix.inputs[0])
    LK(nt, lnorm, nmix.inputs[4])
    LK(nt, geo.outputs["Normal"], nmix.inputs[5])
    LK(nt, nmix.outputs[1], bump.inputs["Normal"])
    LK(nt, bump.outputs[0], leather.inputs["Normal"])
    gn = noise(nt, geo.outputs["Position"], 900.0, 1.0, 0.6)
    gr = maprange(nt, gn.outputs[0], 0.3, 0.7, 0.09, 0.22)
    gcol = mixrgb(nt, maprange(nt, gn.outputs[0], 0.3, 0.7, 0.0, 1.0), GOLD_RGB, GOLD_RGB2)
    gold = principled(nt, **{"Base Color": gcol, "Metallic": 1.0, "Roughness": gr, "Normal": bump.outputs[0],
                             "Specular Tint": (1.0, 0.9, 0.7)})
    mix = NN(nt, "ShaderNodeMixShader")
    LK(nt, foil_f, mix.inputs[0])
    LK(nt, leather.outputs[0], mix.inputs[1])
    LK(nt, gold.outputs[0], mix.inputs[2])
    LK(nt, mix.outputs[0], out.inputs["Surface"])
    return m


def mat_page_edge(name="page_edge", dark=1.0):
    if _simple("edge"):
        return mat_simple(name, PAPER_RGB, 0.6)
    """Edges of a stacked text block: cream with per-leaf striation (attribute 'layer' = leaf index)."""
    m, nt, out = new_mat(name)
    at = NN(nt, "ShaderNodeAttribute", attribute_name="layer")
    geo = NN(nt, "ShaderNodeNewGeometry")
    lay = at.outputs["Fac"]
    fl = math_node(nt, "FLOOR", lay)
    cmb = NN(nt, "ShaderNodeCombineXYZ")
    LK(nt, fl, cmb.inputs[0])
    wn = NN(nt, "ShaderNodeTexWhiteNoise", noise_dimensions="1D")
    LK(nt, fl, wn.inputs["W"])
    per = maprange(nt, wn.outputs["Value"], 0, 1, 0.80, 1.04)
    # one leaf is ~0.1 mm: below a pixel beyond ~0.3 m -> fade the per-leaf terms out with distance
    # (otherwise they alias into granite-like speckle); the 16-leaf signature seams stay
    cdd = NN(nt, "ShaderNodeCameraData")
    near = maprange(nt, cdd.outputs["View Distance"], 0.22, 0.36, 1.0, 0.0)
    per = math_node(nt, "ADD", math_node(nt, "MULTIPLY", math_node(nt, "SUBTRACT", per, vb=0.92), near), vb=0.92)
    band = noise(nt, None, 1.0, 2.0, 0.5, dim="1D")
    LK(nt, math_node(nt, "MULTIPLY", lay, vb=0.06), band.inputs["W"])
    bandv = maprange(nt, band.outputs[0], 0.30, 0.70, 0.74, 1.08)
    # signatures (16 leaves) leave faint darker seams on the edge
    sig = math_node(nt, "FRACT", math_node(nt, "MULTIPLY", lay, vb=1 / 16))
    sigv = maprange(nt, sig, 0.0, 0.07, 0.86, 1.0)
    bandv = math_node(nt, "MULTIPLY", bandv, sigv)
    fr = math_node(nt, "FRACT", lay)
    gap = maprange(nt, math_node(nt, "ABSOLUTE", math_node(nt, "SUBTRACT", fr, vb=0.5)), 0.38, 0.5, 1.0, 0.8)
    gap = math_node(nt, "ADD", math_node(nt, "MULTIPLY", math_node(nt, "SUBTRACT", gap, vb=0.95), near), vb=0.95)
    dirt = noise(nt, geo.outputs["Position"], 60.0, 1.0, 0.5)
    dirtv = maprange(nt, dirt.outputs[0], 0.4, 0.7, 1.0, 0.9)
    v = math_node(nt, "MULTIPLY", math_node(nt, "MULTIPLY", per, bandv), math_node(nt, "MULTIPLY", gap, dirtv))
    base = mixrgb(nt, 1.0, (0.80 * dark, 0.70 * dark, 0.52 * dark), v, "MULTIPLY")
    bmp = NN(nt, "ShaderNodeBump")
    bmp.inputs["Strength"].default_value = 0.25
    bmp.inputs["Distance"].default_value = 0.00005
    LK(nt, math_node(nt, "MULTIPLY", per, gap), bmp.inputs["Height"])
    p = principled(nt, **{"Base Color": base, "Roughness": 0.78, "Normal": bmp.outputs[0]})
    LK(nt, p.outputs[0], out.inputs["Surface"])
    return m


def mask_lod(nt, path, vec):
    """Sharp mask close to the camera, box-filtered copy (made by the design step) further away, so
    tiny print never aliases into denoiser mottle."""
    a = img_node(nt, path, True, vec=vec, ext="CLIP", interp="Cubic")
    b = img_node(nt, path[:-4] + "_lo.png", True, vec=vec, ext="CLIP", interp="Linear")
    cd = NN(nt, "ShaderNodeCameraData")
    f = maprange(nt, cd.outputs["View Distance"], 0.45, 0.70, 0.0, 1.0)
    mx = NN(nt, "ShaderNodeMix"); mx.data_type = "FLOAT"
    LK(nt, f, mx.inputs[0]); LK(nt, a.outputs[0], mx.inputs[2]); LK(nt, b.outputs[0], mx.inputs[3])
    return mx.outputs[0]


def page_ink(nt, num, uv):
    """Ink coverage of page `num` at page UV (u across, v tail->head): crisp running head (number,
    title, rule) + always-blurred body print."""
    d = DESIGN_DIR
    sep = NN(nt, "ShaderNodeSeparateXYZ")
    LK(nt, uv, sep.inputs[0])
    hv = NN(nt, "ShaderNodeCombineXYZ")
    LK(nt, sep.outputs[0], hv.inputs[0])
    LK(nt, maprange(nt, sep.outputs[1], 1 - HEAD_H / PAGE_H, 1.0, 0.0, 1.0, clamp=False), hv.inputs[1])
    head = mask_lod(nt, os.path.join(d, "head_%d.png" % num), hv.outputs[0])
    soft = img_node(nt, os.path.join(d, "body_%d_soft.png" % num), True, vec=uv, ext="CLIP", interp="Linear")
    xsoft = img_node(nt, os.path.join(d, "body_%d_xsoft.png" % num), True, vec=uv, ext="CLIP", interp="Linear")
    # the closer the camera, the stronger the pre-blur (keeps the blur roughly constant on screen, so
    # the body never becomes legible in the macro shots)
    cd = NN(nt, "ShaderNodeCameraData")
    fsoft = maprange(nt, cd.outputs["View Distance"], 0.22, 0.42, 0.0, 1.0)
    mx = NN(nt, "ShaderNodeMix"); mx.data_type = "FLOAT"
    LK(nt, fsoft, mx.inputs[0]); LK(nt, xsoft.outputs[0], mx.inputs[2]); LK(nt, soft.outputs[0], mx.inputs[3])
    # blurred print has a lower peak: lift it back to a believable ink density
    lift = maprange(nt, fsoft, 0.0, 1.0, 1.45, 1.0)
    bk = math_node(nt, "MINIMUM", math_node(nt, "MULTIPLY", mx.outputs[0], lift), vb=1.0)
    # gentle stretch (review 2: 0.02-0.62 -> 0-0.88 turned the blurred lines back into bold word shapes)
    bk = maprange(nt, bk, 0.0, 0.9, 0.0, 0.8)
    return math_node(nt, "MAXIMUM", head, bk)


def _paper_and_ink(nt, ink_cov, geo, tone=1.0):
    """Returns (base_color_socket, roughness_socket, ink_factor_socket)."""
    pn = noise(nt, geo.outputs["Position"], 14.0, 1.0, 0.5)
    tonev = maprange(nt, pn.outputs[0], 0.35, 0.65, 0.95, 1.03)
    paper = mixrgb(nt, 1.0, tuple(c * tone for c in PAPER_RGB), tonev, "MULTIPLY")
    ink = maprange(nt, ink_cov, 0.05, 0.75, 0.0, 0.96)
    col = mixrgb(nt, ink, paper, (0.016, 0.014, 0.013))
    rough = maprange(nt, ink, 0, 1, 0.62, 0.42)
    return col, rough, ink


def mat_page(name, num, uv="UVMap"):
    if _simple("paper"):
        return mat_simple(name, PAPER_RGB, 0.6)
    m, nt, out = new_mat(name)
    geo = NN(nt, "ShaderNodeNewGeometry")
    uvn = NN(nt, "ShaderNodeUVMap", uv_map=uv)
    col, rough, ink = _paper_and_ink(nt, page_ink(nt, num, uvn.outputs[0]), geo)
    p = principled(nt, **{"Base Color": col, "Roughness": rough})
    LK(nt, p.outputs[0], out.inputs["Surface"])
    return m


def mat_leaf(name, num_front, num_back):
    """Single sheet: recto on the front face, verso (mirrored) on the back face, with a little
    translucency so the other side's print shows through faintly when backlit."""
    if _simple("paper"):
        return mat_simple(name, PAPER_RGB, 0.6)
    m, nt, out = new_mat(name)
    geo = NN(nt, "ShaderNodeNewGeometry")
    uvn = NN(nt, "ShaderNodeUVMap", uv_map="UVMap")
    sep = NN(nt, "ShaderNodeSeparateXYZ")
    LK(nt, uvn.outputs[0], sep.inputs[0])
    cmb = NN(nt, "ShaderNodeCombineXYZ")
    LK(nt, math_node(nt, "SUBTRACT", va=1.0, b=sep.outputs[0]), cmb.inputs[0])
    LK(nt, sep.outputs[1], cmb.inputs[1])
    f = page_ink(nt, num_front, uvn.outputs[0])
    b = page_ink(nt, num_back, cmb.outputs[0])
    bf = geo.outputs["Backfacing"]
    this = NN(nt, "ShaderNodeMix"); this.data_type = "FLOAT"
    LK(nt, bf, this.inputs[0]); LK(nt, f, this.inputs[2]); LK(nt, b, this.inputs[3])
    other = NN(nt, "ShaderNodeMix"); other.data_type = "FLOAT"
    LK(nt, bf, other.inputs[0]); LK(nt, b, other.inputs[2]); LK(nt, f, other.inputs[3])
    col, rough, ink = _paper_and_ink(nt, this.outputs[0], geo)
    p = principled(nt, **{"Base Color": col, "Roughness": rough})
    tcol = mixrgb(nt, maprange(nt, other.outputs[0], 0.1, 0.9, 0.0, 0.30), tuple(c * 0.9 for c in PAPER_RGB), (0.1, 0.09, 0.08))
    tr = NN(nt, "ShaderNodeBsdfTranslucent")
    LK(nt, tcol, tr.inputs["Color"])
    mix = NN(nt, "ShaderNodeMixShader")
    mix.inputs[0].default_value = 0.14
    LK(nt, p.outputs[0], mix.inputs[1]); LK(nt, tr.outputs[0], mix.inputs[2])
    LK(nt, mix.outputs[0], out.inputs["Surface"])
    return m


def mat_headband(name="headband"):
    m, nt, out = new_mat(name)
    geo = NN(nt, "ShaderNodeNewGeometry")
    w = NN(nt, "ShaderNodeTexWave")
    w.wave_type = "BANDS"
    w.bands_direction = "X"
    w.inputs["Scale"].default_value = 260.0
    LK(nt, geo.outputs["Position"], w.inputs["Vector"])
    col = mixrgb(nt, maprange(nt, w.outputs["Fac"], 0.45, 0.55, 0, 1), srgb("#7E1D20"), srgb("#E3D3A6"))
    p = principled(nt, **{"Base Color": col, "Roughness": 0.55, "Sheen Weight": 0.6})
