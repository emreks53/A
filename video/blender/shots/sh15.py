def pseudo_text(rng, n_words, cap_chance=0.07):
    words = []
    new_sentence = True
    for i in range(n_words):
        k = rng.choice((1, 1, 2, 2, 2, 3, 3, 4))
        w = "".join(rng.choice(_SYL) for _ in range(k))
        if rng.random() < 0.12:
            w = rng.choice(("ve", "bu", "bir", "o", "ki", "her", "da", "de", "ile", "ne"))
        if new_sentence or rng.random() < cap_chance:
            w = w[0].upper().replace("i", "İ") + w[1:] if w[0] != "i" else "İ" + w[1:]
            new_sentence = False
        r = rng.random()
        if r < 0.075:
            w += ","
        elif r < 0.115:
            w += "."
            new_sentence = True
        elif r < 0.12:
            w += ":"
        words.append(w)
    return " ".join(words)


def draw_page(P, num, rng, W, H):
    """Ink of one page; (0,0) bottom-left; recto pages (odd) have the outer margin on the right."""
    recto = num % 2 == 1
    inner, outer, top, bottom = 0.020, 0.015, 0.020, 0.024
    x0 = inner if recto else outer
    x1 = W - (outer if recto else inner)
    tw = x1 - x0
    # running header
    hy = H - 0.0135
    P.text("SÖZLER", "ebg_reg", 0.0023, (x0 + x1) / 2, hy, spacing=1.35)
    P.text(str(num), "ebg_med", 0.0030, x1 if recto else x0, hy, align="RIGHT" if recto else "LEFT")
    P.rect(x0, hy - 0.0030, x1, hy - 0.00265)
    # body paragraphs
    size = 0.0046
    paras = []
    for k in range(30):
        paras.append("    " + pseudo_text(rng, rng.randint(25, 90)))
    body = "\n".join(paras)
    has_note = rng.random() < 0.6
    bottom_body = bottom + (0.020 if has_note else 0.0)
    P.textbox(body, "ebg_reg", size, x0, H - top - 0.0045, tw, H - top - bottom_body - 0.003, line=1.0)
    if has_note:
        ny = bottom + 0.0185
        P.rect(x0, ny, x0 + tw * 0.28, ny + 0.0003)
        P.textbox("* " + pseudo_text(rng, 40), "ebg_reg", 0.0030, x0, ny - 0.0045, tw, 0.0165, line=1.0)


RAHLE_LEN, RAHLE_W, RAHLE_LOW = 0.50, 0.26, 0.21     # board length, width, leg length (from hinge)


def star_ring(cx, cy, ro, ri, k=8, rot=0.0):
    pts = []
    for i in range(2 * k):
        r = ro if i % 2 == 0 else ri
        a = rot + math.pi * i / k
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


RELIEF_PANELS = [(-0.128, -0.034), (0.034, 0.206)]     # board-local l ranges of the carved panels
RELIEF_YM = 0.012                                       # panel margin from the board's long edges


def relief_panel(P, x0, y0, x1, y1, s):
    """Carved panel height map (0 = board surface at the panel rim, 1 = top of the carving):
    raised frame, sunk ground, interlaced 8-point star strapwork, rosette bosses."""
    P.rect(x0 + 0.0012, y0 + 0.0012, x1 - 0.0012, y1 - 0.0012, v=0.30).location.z = 0.0005
    P.frame(x0 + 0.0012, y0 + 0.0012, x1 - 0.0012, y1 - 0.0012, 0.0062, v=1.0).location.z = 0.001
    P.frame(x0 + 0.0095, y0 + 0.0095, x1 - 0.0095, y1 - 0.0095, 0.0024, v=0.80).location.z = 0.001
    fx0, fy0, fx1, fy1 = x0 + 0.015, y0 + 0.015, x1 - 0.015, y1 - 0.015
    nx = max(1, int(round((fx1 - fx0) / s))); ny = max(1, int(round((fy1 - fy0) / s)))
    sx = (fx1 - fx0) / nx; sy = (fy1 - fy0) / ny
    r = min(sx, sy) * 0.5
    for i in range(nx):
        for j in range(ny):
            cx, cy = fx0 + (i + 0.5) * sx, fy0 + (j + 0.5) * sy
            P.stroke(star_ring(cx, cy, r * 0.97, r * 0.68, 8, 0.0), 0.0048, v=1.0, closed=True, z=0.002)
            P.stroke(star_ring(cx, cy, r * 0.50, r * 0.34, 8, math.pi / 8), 0.0030, v=0.85, closed=True, z=0.002)
            P.disc(cx, cy, r * 0.15, n=20, v=0.95).location.z = 0.002
    for i in range(nx + 1):
        for j in range(ny + 1):
            cx, cy = fx0 + i * sx, fy0 + j * sy
            P.stroke(star_ring(cx, cy, r * 0.40, r * 0.18, 4, math.pi / 4), 0.0034, v=0.95, closed=True, z=0.002)


def draw_relief(P, L, Wd):
    """Rahle carving height map for one board (x = l + RAHLE_LOW along the board, y across)."""
    P.rect(-0.01, -0.01, L + 0.01, Wd + 0.01, v=0.0, z=-0.01)
    for (l0, l1) in RELIEF_PANELS:
        relief_panel(P, l0 + RAHLE_LOW, RELIEF_YM, l1 + RAHLE_LOW, Wd - RELIEF_YM, 0.056)


