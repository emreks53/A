# ----------------------------------------------------------------------------- rahle (carved folding stand)

RAHLE_LU = RAHLE_LEN - RAHLE_LOW          # upper arm length 0.33
RAHLE_HZ = 0.019                          # hinge zone half length
RAHLE_LL_EXT = RAHLE_LOW + 0.014


def rahle_hinge_z():
    return RAHLE_LOW * math.sin(BETA) + RAHLE_TB / 2 * math.cos(BETA)


def rahle_v0():
    """Crotch point where the two arms' upper surfaces meet (rahle-local x=0)."""
    return rahle_hinge_z() + (RAHLE_TB / 2) / math.cos(BETA)


def _extrude_outline(bm, outline, t0, t1, uv, uvr_fn):
    """Extrude a 2D (l, y) polygon between t0 and t1 into bm (ngon caps)."""
    vb = [bm.verts.new((l, y, t0)) for (l, y) in outline]
    vt = [bm.verts.new((l, y, t1)) for (l, y) in outline]
    n = len(outline)
    faces = []
    for i in range(n):
        i2 = (i + 1) % n
        faces.append(bm.faces.new((vb[i], vb[i2], vt[i2], vt[i])))
    faces.append(bm.faces.new(vb[::-1]))
    faces.append(bm.faces.new(vt))
    for f in faces:
        for lp in f.loops:
            lp[uv].uv = uvr_fn(lp.vert.co)
    return faces


def carve_panels(name, M, mat, relief_path, step=0.0013, depth=0.0024):
    """Real displaced geometry for the carved panels on both faces of one board (board-local frame
    l, y, t; M = board world matrix)."""
    RW, tb = RAHLE_W, RAHLE_TB
    tex = bpy.data.textures.get("relief_tex")
    if tex is None:
        tex = bpy.data.textures.new("relief_tex", "IMAGE")
        img = bpy.data.images.load(relief_path, check_existing=True)
        img.colorspace_settings.name = "Non-Color"
        tex.image = img
        tex.extension = "EXTEND"
    bm = bmesh.new()
    uv = bm.loops.layers.uv.new("uvr")
    y0, y1 = -RW / 2 + RELIEF_YM, RW / 2 - RELIEF_YM
    for (l0, l1) in RELIEF_PANELS:
        nl = int((l1 - l0) / step); ny = int((y1 - y0) / step)
        for fs in (1, -1):
            # faces looking down (under the X / under the arms) are never seen by a camera: no carving
            if (M.to_3x3() @ Vector((0, 0, fs))).z < -0.1:
                continue
            V = [[bm.verts.new((l0 + (l1 - l0) * i / nl, y0 + (y1 - y0) * j / ny, fs * (tb / 2 + 0.00004)))
                  for j in range(ny + 1)] for i in range(nl + 1)]
            for i in range(nl):
                for j in range(ny):
                    q = (V[i][j], V[i + 1][j], V[i + 1][j + 1], V[i][j + 1])
                    f = bm.faces.new(q if fs > 0 else q[::-1])
                    for lp in f.loops:
                        co = lp.vert.co
                        lp[uv].uv = ((co.x + RAHLE_LOW) / RAHLE_LEN, (co.y + RW / 2) / RW)
    ob = bm_to_obj(bm, name, mats=[mat], smooth=True)
    ob.matrix_world = M
    d = ob.modifiers.new("carve", "DISPLACE")
    d.texture = tex
    d.texture_coords = "UV"
    d.uv_layer = "uvr"
    d.mid_level = 0.0
    d.strength = depth
    d.direction = "NORMAL"
    return ob


def build_rahle(mat, relief_path=None):
    RW = RAHLE_W
    tb = RAHLE_TB
    zh = rahle_hinge_z()
    objs = []
    crest = 0.075
    foot = 0.050
    arch_h = 0.085
    nseg = 7
    seg = RW / nseg

    def uvr_fn(co):
        return ((co.x + RAHLE_LOW) / RAHLE_LEN, (co.y + RW / 2) / RW)

    for side in (1, -1):
        bm = bmesh.new()
        uv = bm.loops.layers.uv.new("uvr")
        # arm with ogee crest
        arm = [(RAHLE_HZ, -RW / 2)]
        N = 28
        for k in range(N + 1):
            yy = -RW / 2 + (RW / 2) * k / N
            x = abs(yy) / (RW / 2)
            g = (x * x * (3 - 2 * x)) ** 0.72
            g += 0.05 * math.sin(math.pi * x) ** 2 * math.sin(3 * math.pi * x)
            arm.append((RAHLE_LU - crest * g, yy))
        for k in range(N - 1, -1, -1):
            l, yy = arm[1 + k]
            arm.append((l, -yy))
        arm.append((RAHLE_HZ, RW / 2))
        _extrude_outline(bm, arm, -tb / 2, tb / 2, uv, uvr_fn)
        # leg with pointed-arch cut-out between two feet
        leg = [(-RAHLE_HZ, -RW / 2), (-RAHLE_HZ, RW / 2), (-RAHLE_LL_EXT, RW / 2)]
        y0 = RW / 2 - foot
        for k in range(N + 1):
            yy = y0 - (2 * y0) * k / N
            x = abs(yy) / y0
            leg.append((-RAHLE_LL_EXT + arch_h * (max(0.0, 1 - x ** 1.7)) ** 0.62, yy))
        leg.append((-RAHLE_LL_EXT, -RW / 2))
        _extrude_outline(bm, leg, -tb / 2, tb / 2, uv, uvr_fn)
        # hinge knuckles: alternate segments for the two boards, rounded barrels
        for k in range(nseg):
            if (k % 2 == 0) != (side == 1):
                continue
            ya, yb = -RW / 2 + k * seg + 0.0006, -RW / 2 + (k + 1) * seg - 0.0006
            ring_a, ring_b = [], []
            M = 28
            rk = 0.0118
            for i in range(M):
                a = 2 * math.pi * i / M
                l, t = rk * math.cos(a), rk * 0.80 * math.sin(a)
                ring_a.append(bm.verts.new((l, ya, t)))
                ring_b.append(bm.verts.new((l, yb, t)))
            fs = []
            for i in range(M):
                i2 = (i + 1) % M
                fs.append(bm.faces.new((ring_a[i], ring_a[i2], ring_b[i2], ring_b[i])))
            fs.append(bm.faces.new(ring_a[::-1])); fs.append(bm.faces.new(ring_b))
            box = [(-RAHLE_HZ - 0.002, ya), (RAHLE_HZ + 0.002, ya), (RAHLE_HZ + 0.002, yb), (-RAHLE_HZ - 0.002, yb)]
            fs += _extrude_outline(bm, box, -tb / 2, tb / 2, uv, uvr_fn)
            for f in fs:
                for lp in f.loops:
                    lp[uv].uv = uvr_fn(lp.vert.co)
        # board rotation: l -> e, y -> Y, t -> e x Y
        e = Vector((side * math.cos(BETA), 0, math.sin(BETA)))
        nrm = e.cross(Vector((0, 1, 0)))
        R = Matrix((e, Vector((0, 1, 0)), nrm)).transposed()
        # flat feet: slide vertices below the table plane back along the board
        for v in bm.verts:
            w = R @ v.co
            if zh + w.z < 0:
                l_new = (-zh - v.co.z * nrm.z) / e.z
                v.co.x = l_new
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
        ob = bm_to_obj(bm, "rahle_%s" % ("A" if side > 0 else "B"), mats=[mat], smooth=True, sharp_angle=35)
        ob.matrix_world = Matrix.Translation(RAHLE_POS) @ Matrix.Rotation(RAHLE_YAW, 4, "Z") @ Matrix.Translation((0, 0, zh)) @ R.to_4x4()
        add_bevel(ob, 0.0018, 3, 35)
        objs.append(ob)
        if relief_path:
            objs.append(carve_panels(ob.name + "_carve", ob.matrix_world.copy(), mat, relief_path))
    # wooden hinge pin ends (tiny dowel caps on the outer knuckles)
    return objs


